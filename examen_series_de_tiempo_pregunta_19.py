# Function for correlogram (ACF and PACF)
def correlogram(series, name, lags=10):
    acf_values = acf(series, nlags=lags, fft=False)
    pacf_values = pacf(series, nlags=lags)

    # Create table
    corr_table = pd.DataFrame({
        'Lag': range(1, lags + 1),
        'ACF': acf_values[1:lags + 1],
        'PACF': pacf_values[1:lags + 1]
    })
    print(f"\nCorrelogram for {name} (first {lags} lags):")
    print(corr_table)

    # Plot ACF and PACF
    plt.figure(figsize=(12, 6))
    plt.subplot(121)
    plt.stem(range(1, lags + 1), acf_values[1:lags + 1])
    plt.title(f'{name} ACF')
    plt.xlabel('Lag')
    plt.ylabel('Autocorrelation')

    plt.subplot(122)
    plt.stem(range(1, lags + 1), pacf_values[1:lags + 1])
    plt.title(f'{name} PACF')
    plt.xlabel('Lag')
    plt.ylabel('Partial Autocorrelation')
    plt.tight_layout()
    plt.show()

