# Function to extract and clean series
def extract_series(df, column_name, series_name):
    try:
        values = df[column_name]
        # Convert to numeric, coercing errors to NaN
        values = pd.to_numeric(values, errors='coerce')
        # Check for non-numeric or missing values
        if values.isna().any():
            print(f"Warning: {series_name} contains {values.isna().sum()} non-numeric or missing values")
        # Drop NaN values
        values = values.dropna()
        return values
    except KeyError:
        print(f"Error: Column '{column_name}' not found in DataFrame")
        print("Please check the column name and try again")
        raise

